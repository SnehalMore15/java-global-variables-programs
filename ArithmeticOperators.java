package com.tka;

public class ArithmeticOperators {
	
	public static void main(String[] args) {
		int x = 8;
		int y = 11;
		
	System.out.println("The Addition of " +x+ "+" +y+ " = " + (x+y));
	System.out.println("The Substractin of " +x+ "-" +y+ " = " + (x-y));
	System.out.println("The Multiplication of " +x+ "*" +y+ " = " + (x*y));
	System.out.println("The Division of " +x+ "/" +y+ " = " + (x/y));
	System.out.println("The Modules of " +x+ "%" +y+ " = " + (x%y));


}
}