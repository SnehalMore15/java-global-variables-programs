package com.tka;

public class IncrementDecrementOperator {
	public static void main(String[] args) {
		 
		int a = 34;
		a++;    //35
		a--;     //34
		System.out.println(a++);  //34
		--a;   //34
		++a;   //35
		System.out.println(a++);  // 35
		a--;   //35
		a--;   //34
		a++;   //35
		System.out.println(--a);   //34
		a++; //35
		a--; //34
		a++;  //35
		System.out.println(a+4); //39
		a--;  //34
		System.out.println(--a);  // 33
		a--;  //32
		a++;  //33
		a--;   //32
		System.out.println(a);
		
		

	}

}
